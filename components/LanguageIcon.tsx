const normalize = (value: string) => value.toLowerCase().replace(/[^a-z0-9]/g, "");

const normalized = new Map<string, SimpleIcon>();
for (const [language, icon] of Object.entries(icons)) {
  normalized.set(normalize(language), icon);
}

export function getLanguageIcon(language: string): SimpleIcon | undefined {
  return icons[language] ?? normalized.get(normalize(language));
}

export function LanguageIcon({
  icon,
  className,
}: {
  icon: SimpleIcon;
  className?: string;
}) {
  return (
    <svg
      aria-hidden="true"
      viewBox="0 0 24 24"
      className={className}
      fill={`#${icon.hex}`}
    >
      <path d={icon.path} />
    </svg>
  );
}
